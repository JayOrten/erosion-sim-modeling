"""Training profiles for the single-window models (see docs/plans/)."""

from dataclasses import dataclass, replace


OBJECTIVES = ("regression", "diffusion")
LEVELS = (None, "coarse", "fine")


@dataclass(frozen=True)
class Config:
    """Settings for one training run. Checkpoints go to artifacts/checkpoints/<objective>-<profile>.pt."""

    profile: str
    data_profile: str  # dataset under artifacts/data/, generated by datagen/
    # "regression": predict the change directly with MSE. "diffusion": sample it with a denoiser.
    objective: str = "regression"
    # Which runs to use, as (parameter, (low, high)) pairs; see data.select_runs. Empty uses every run.
    runs: tuple[tuple[str, tuple[float, float]], ...] = ()
    # Elapsed times to train on, in snapshot steps (1 = 1,000 yr in the full dataset). None uses all.
    lags: tuple[int, ...] | None = None
    # Edge cells change by zero, as in the simulator. False for world models, whose window edges are not
    # boundaries.
    fixed_edges: bool = True
    # World level (docs/plans/infinite-plan.md, step 5). None trains on whole runs (ErosionPairs).
    # "coarse": whole runs as block x block means (world.data.ErosionCoarse). "fine": crop x crop pieces
    # with the true coarse change as a second input channel (world.data.ErosionCrops).
    level: str | None = None
    crop: int = 64
    block: int = 4
    # Coarse level only: crop the block means to this many coarse cells per side. None uses whole runs.
    coarse_crop: int | None = None
    # World levels: keep crops this many fine cells away from the run's edge, where the simulator holds
    # heights fixed and drains water (infinite-plan step 9a).
    margin: int = 0
    # World levels: training items per (run, start, end) pair, each its own crop and flip.
    repeats: int = 1
    max_train_samples: int | None = None  # train on only this many fixed pairs (for the overfit test)
    # Model
    channels: tuple[int, ...] = (32, 64, 128, 256)
    blocks: int = 1
    emb_dim: int = 256
    attention: bool = True
    # Optimization
    batch_size: int = 32
    lr: float = 3e-4
    weight_decay: float = 1e-4
    steps: int = 20_000
    epochs: float | None = None  # if set, replaces steps: this many passes over the training pairs
    warmup_steps: int = 500
    # Exponential moving average of the weights, used for validation and saved as the model. Each step
    # moves the average 1 - ema_decay of the way to the training weights, so it covers about
    # 1 / (1 - ema_decay) steps. None turns it off.
    ema_decay: float | None = 0.999
    # Validation
    eval_every: int = 1_000
    val_samples: int = 2_048  # fixed validation pairs, drawn once
    patience: int | None = None  # stop after this many evaluations without a better validation loss
    log_every: int = 100
    # Hardware
    num_workers: int = 8
    compile: bool = True  # torch.compile; ignored on CPU
    bf16: bool = True  # 16-bit autocast; ignored on CPU
    seed: int = 0

    def __post_init__(self):
        if self.objective not in OBJECTIVES:
            raise ValueError(f"objective must be one of {OBJECTIVES}, got {self.objective!r}")
        if self.level not in LEVELS:
            raise ValueError(f"level must be one of {LEVELS}, got {self.level!r}")
        if self.margin % self.block:
            raise ValueError("margin must be a multiple of block")

    @property
    def in_channels(self) -> int:
        """Input channels besides the noisy target: the start heightmap, plus the coarse change at the fine level."""
        return 2 if self.level == "fine" else 1


PROFILES = {
    # Seconds on CPU, for tests. Point data_root at a small dataset.
    "smoke": Config(
        profile="smoke",
        data_profile="smoke",
        channels=(8, 16),
        emb_dim=16,
        batch_size=4,
        steps=6,
        warmup_steps=2,
        ema_decay=0.5,
        eval_every=3,
        val_samples=8,
        log_every=2,
        num_workers=0,
        compile=False,
    ),
    # Memorize 10 pairs. If the loss does not go near zero, the pipeline is broken.
    "overfit": Config(
        profile="overfit",
        data_profile="full",
        max_train_samples=10,
        batch_size=10,
        lr=1e-3,
        weight_decay=0.0,
        steps=2_000,
        warmup_steps=50,
        ema_decay=0.99,
        eval_every=500,
        val_samples=256,
        num_workers=2,
        compile=False,
    ),
    # One elapsed time (10,000 yr), no uplift. Step 9 of docs/plans/unet-baseline-plan.md.
    "fixed_dt": Config(
        profile="fixed_dt",
        data_profile="full",
        runs=(("U", (0.0, 0.0)),),
        lags=(10,),
        steps=20_000,
    ),
    # Every elapsed time, no uplift. One pass over every pair, about 53,000 steps at batch 64. Step 10 of
    # docs/plans/unet-baseline-plan.md.
    "variable_dt": Config(
        profile="variable_dt",
        data_profile="full",
        runs=(("U", (0.0, 0.0)),),
        epochs=1.0,
        patience=10,
        batch_size=64,
    ),
    # The two levels of the infinite world (docs/plans/infinite-plan.md, step 5), trained as diffusion
    # models. Every elapsed time, no uplift, and free edges. Short budgets: the
    # first goal is output that is sensible, not good.
    "world_coarse": Config(
        profile="world_coarse",
        data_profile="world",
        runs=(("U", (0.0, 0.0)),),
        fixed_edges=False,
        level="coarse",
        batch_size=64,
        steps=20_000,
    ),
    "world_fine": Config(
        profile="world_fine",
        data_profile="world",
        runs=(("U", (0.0, 0.0)),),
        fixed_edges=False,
        level="fine",
        batch_size=64,
        steps=20_000,
    ),
}


def get_config(profile: str, objective: str = "regression") -> Config:
    """The settings for ``profile``, trained with ``objective``. Profiles set the data and model size; the
    objective is chosen separately, so every profile works with both."""
    return replace(PROFILES[profile], objective=objective)
